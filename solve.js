// Fast drop-in for makefun-site 1.0.0 — an original, dependency-free reimplementation
// of its build, written from its README and reference behaviour so that run(input)
// returns byte-for-byte the same answer for every input, faster.
//
// Design notes (all semantics match the reference exactly; only the work differs):
// - Markdown is rendered in a single pass over the body's lines: no token array is
//   built, and inline rendering accumulates into an array joined once at the end.
// - Template rendering writes into an output array instead of concatenating strings.
// - slugify results are cached per case (titles and tag names repeat across a site).
// - A page's card is computed once per source and reused by its layout and the lists.
// - Word counting scans for whitespace runs without allocating a match array.

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

